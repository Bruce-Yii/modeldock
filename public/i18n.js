let currentLang = "en";
let t = (key, params) => {
  const table = currentLang === "zh" ? I18N_ZH : I18N_EN;
  let text = table[key] ?? I18N_EN[key] ?? key;
  if (params) for (const [name, value] of Object.entries(params)) text = text.replaceAll(`{${name}}`, value);
  return text;
};

function setLang(lang) {
  currentLang = lang === "zh" ? "zh" : "en";
  document.documentElement.lang = currentLang === "zh" ? "zh-CN" : "en";
  try { localStorage.setItem("modeldock-lang", currentLang); } catch {}
}

function getLang() {
  return currentLang;
}

function initI18n() {
  let lang = null;
  try { lang = localStorage.getItem("modeldock-lang"); } catch {}
  if (lang !== "zh" && lang !== "en") lang = (navigator.language || "en").toLowerCase().startsWith("zh") ? "zh" : "en";
  setLang(lang);
  applyStaticI18n();
  if (typeof refreshDynamicText === "function") refreshDynamicText();
}

function applyStaticI18n() {
  document.querySelectorAll("[data-i18n]").forEach((node) => { node.textContent = t(node.dataset.i18n); });
}

export { t, getLang, setLang, initI18n, applyStaticI18n };
